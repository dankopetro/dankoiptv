from PyQt6 import QtCore
from dankoiptv_lib.misc import DankoData


def get_qt_info(app):
    if not DankoData.qt_info:
        DankoData.qt_info = f"{QtCore.qVersion()} ({app.platformName()})"
    return DankoData.qt_info
